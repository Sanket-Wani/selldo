DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = 'selldo_app') THEN
    CREATE ROLE selldo_app WITH LOGIN PASSWORD 'selldo_secure_pass' NOSUPERUSER NOCREATEDB NOCREATEROLE;
  END IF;
END $$;

GRANT ALL PRIVILEGES ON DATABASE selldo TO selldo_app;
GRANT ALL ON SCHEMA public TO selldo_app;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public TO selldo_app;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public TO selldo_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO selldo_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO selldo_app;
